import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Antichess} from 'chessops/variant';
import {parseSan} from 'chessops/san';

// User-directed White repertoire, extended along the named catalog's
// Andrejić's Proof branch. Legacy numeric rankings do not select these moves.
const snapshot=JSON.parse(fs.readFileSync(new URL('../studies/polish/current-explorer-snapshot.json',import.meta.url),'utf8'));
const repertoire=['e3','c5','Ba6','Nxa6','b4','cxb4','d3','b3','cxb3','Nc7','b4','Ne6','d4','Nxd4','Qxd4','Qc7'];
for(let i=7;i<repertoire.length;i++) {
 const parent=repertoire.slice(0,i).join('_');
 const child=repertoire.slice(0,i+1).join('_');
 const position=snapshot.positions.find(p=>p.pgn===parent);
 assert.ok(position?.moves.some(m=>m.pgn===child),`Missing catalog evidence: ${child}`);
}
const chapters=[
 {title:'The main opening through 4. d3',end:7},
 {title:'4...b3: the Nc7–Ne6 branch',end:16},
];
const comments=[
 'White opens the bishop’s diagonal.',
 '',
 'White offers the bishop on a6.',
 'This is the Polish Defense position.',
 'Advance the b-pawn to draw Black’s c-pawn away from c5.',
 'Black captures with the c-pawn. White now has the position we want.',
 'The key move in this repertoire is d3. The next chapters follow Black’s b3 response.',
 '',
 'The c-pawn recaptures on b3. Keep track of this pawn: its next advance is important.',
 '',
 'Advance the pawn from b3 to b4. This is the continuation to remember after Nc7.',
 '',
 'Offer the d-pawn to the knight on e6.',
 '',
 'Recapture the knight with the queen.',
 'This chapter ends at the opening checkpoint. The rest of the game is not included.',
];
for(const c of chapters){
 const p=Antichess.default();
 for(const san of repertoire.slice(0,c.end)){
  const move=parseSan(p,san);
  assert.ok(move&&p.isLegal(move),`${c.title}: ${san}`);
  p.play(move);
 }
}
const brace=s=>'{ '+s+' }';
const pgn=chapters.map((c,index)=>[
 '[Event "Defeating the Polish Defense"]',
 '[StudyName "Defeating the Polish Defense"]',
 `[ChapterName "${c.title}"]`,'[Variant "Antichess"]','[Result "*"]',
 ...(index===0?[
  '[Source "https://antichess.onrender.com/openings/"]',
  '[Annotator "Antichess Trainer; move references: Antichess Opening Explorer (tolius), with earlier material from Cătălin Frâncu"]',
  '[License "CC BY-SA 3.0; https://creativecommons.org/licenses/by-sa/3.0/"]',
 ]:[]),'',
 brace('Train as White. Replay the opening from the initial position.'),
 repertoire.slice(0,c.end).map((san,i)=>`${i%2===0?`${Math.floor(i/2)+1}. `:''}${san}${comments[i]?' '+brace(comments[i]):''}`).join(' ')+' *',
].join('\n')).join('\n\n')+'\n';
fs.writeFileSync(new URL('../studies/polish/polish-training.pgn',import.meta.url),pgn);
fs.writeFileSync(new URL('../src/polishStudy.ts',import.meta.url),'// Generated by scripts/build-polish.mjs. Module data: CC BY-SA 3.0; see studies/polish/README.md.\nexport const polishStudy = '+JSON.stringify(pgn)+';\n');
console.log('Built 2 White repertoire chapters; 23 legal replayed plies. Unresolved catalog defenses are excluded.');
