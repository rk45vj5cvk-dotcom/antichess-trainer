import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Antichess} from 'chessops/variant';
import {parseSan} from 'chessops/san';
const snapshot=JSON.parse(fs.readFileSync(new URL('../studies/polish/database-snapshot.json',import.meta.url),'utf8'));
const prefix=['e3','c5','Ba6','Nxa6'];
const rank=r=>r.score==='won'?Infinity:r.score==='lost'?-Infinity:Number(r.score);
const intro='Train as Black in the Polish Defense.';
const chapters=[{title:'Meet the Polish Defense',moves:prefix,branch:null,kind:'setup'}];
const firstComments={
 b4:'Use the c-pawn to take on b4, keeping the knight on a6.',
 d4:'The c-pawn takes on d4, opening the c-file.',
 Qh5:'The queen reaches b6 through c7, which was cleared by c5.',
 Qf3:'The queen reaches b6 through c7, which was cleared by c5.',
 Qg4:'The queen reaches b6 through c7, which was cleared by c5.',
};
for(const line of snapshot.lines) {
 assert.deepEqual(line.moves.slice(0,4),prefix);
 assert.equal(line.moves[4],line.branch);
 for(const decision of line.decisions) {
  assert.deepEqual(decision.page.moves,line.moves.slice(0,decision.ply));
  assert.equal(line.moves[decision.ply],decision.selected.move);
  assert.equal(rank(decision.selected),Math.max(...decision.page.rows.map(rank)));
  assert.notEqual(decision.selected.score,'lost');
 }
 const end=line.moves.length-line.moves.length%2;
 chapters.push({title:`3. ${line.branch}: Black’s first response`,moves:line.moves.slice(0,6),branch:line.branch,kind:'response'});
 chapters.push({title:`3. ${line.branch}: opening continuation`,moves:line.moves.slice(0,end),branch:line.branch,kind:'continuation'});
}
for(const c of chapters) {
 const p=Antichess.default();
 assert.equal(c.moves.length%2,0,'Every checkpoint ends after Black moves');
 c.moves.forEach(san=>{const m=parseSan(p,san);assert.ok(m&&p.isLegal(m),`${c.title}: ${san}`);p.play(m);});
}
const comments=(c,i)=>{
 if(i===0)return 'White opens the bishop’s diagonal.';
 if(i===1)return 'Black advances the c-pawn, clearing c7 for the queen.';
 if(i===2)return 'White offers the bishop on a6.';
 if(i===3)return 'Black’s knight captures on a6. This is the Polish Defense starting position.';
 if(i===5)return firstComments[c.branch];
 return '';
};
const brace=s=>'{ '+s+' }';
const pgn=chapters.map((c,index)=>[
 '[Event "Polish Defense — Introduction"]','[StudyName "Polish Defense — Introduction"]',
 `[ChapterName "${c.title}"]`,'[Variant "Antichess"]','[Result "*"]',
 ...(index===0?[
  '[Source "https://catalin.francu.com/nilatac/"]',
  '[Annotator "Adapted from Cătălin Frâncu / Nilatac by Antichess Trainer"]',
  '[License "CC BY-SA 3.0; https://creativecommons.org/licenses/by-sa/3.0/"]',
 ]:[]),'',
 brace(intro),
 c.moves.map((san,i)=>{
  let note=comments(c,i);
  if(i===c.moves.length-1)note+=' '+(c.kind==='continuation'?
   'This is the end of this opening line.':
   c.kind==='response'?'This checkpoint focuses on recognizing the first response. The next chapter extends this branch.':
   'The next chapters cover White’s b4, d4, Qh5, Qf3, and Qg4.');
  return `${i%2===0?`${Math.floor(i/2)+1}. `:''}${san}${note?' '+brace(note):''}`;
 }).join(' ')+' *',
].join('\n')).join('\n\n')+'\n';
fs.writeFileSync(new URL('../studies/polish/polish-training.pgn',import.meta.url),pgn);
fs.writeFileSync(new URL('../src/polishStudy.ts',import.meta.url),'// Generated by scripts/build-polish.mjs. Module data: CC BY-SA 3.0; see studies/polish/README.md.\nexport const polishStudy = '+JSON.stringify(pgn)+';\n');
console.log(`Built ${chapters.length} Polish chapters; ${chapters.reduce((n,c)=>n+c.moves.length,0)} legal plies from the initial position.`);
