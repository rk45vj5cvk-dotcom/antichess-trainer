import fs from 'node:fs';
import {parsePgn} from 'chessops/pgn';
import {Antichess} from 'chessops/variant';
import {parseFen, makeFen} from 'chessops/fen';
import {parseSan} from 'chessops/san';
const games=parsePgn(fs.readFileSync(new URL('../studies/wizard-source.pgn',import.meta.url),'utf8'));
const clean=comments=>(comments||[]).map(c=>c
 .replace(/\[%[^\]]*\]/g,'')
 .replace(/[^.!?\n]*\bquiz\b[^.!?\n]*[.!?]?/gi,'')
 .replace(/Chapter \d+/g,'a separate branch')
 .replace(/(?:the )?(?:next|previous) chapter/gi,'the related branch')
 .trim()).filter(Boolean);
const key=p=>makeFen(p.toSetup()).split(' ').slice(0,4).join(' ');
const initial=Antichess.default();
const paths=new Map([[key(initial),[]]]);
const sources=games.map((g,i)=>({g,index:i+1})).filter(({g})=>!/^quiz\b/i.test(g.headers.get('ChapterName')||''));
// These authored early Black deviations are described in the study comments
// but their source chapters begin after the deviation has already occurred.
for (const deviation of ['Qxh1', 'Qxd2']) {
 const p=initial.clone(), moves=[];
 for (const san of ['c4','d5','cxd5','Qxd5','g4','Bxg4','Qa4',deviation]) {
  const m=parseSan(p,san);
  if(!m||!p.isLegal(m)) throw new Error(`Illegal connecting move: ${san}`);
  p.play(m);moves.push({san,comments:[]});
 }
 paths.set(key(p),moves);
}
const resolved=new Map();
for(let pass=0;pass<games.length;pass++) {
 for(const {g,index} of sources) {
  if(resolved.has(index)) continue;
  const start=Antichess.fromSetup(parseFen(g.headers.get('FEN')).unwrap()).unwrap();
  const prefix=paths.get(key(start));
  if(!prefix) continue;
  const moves=prefix.map(m=>({...m,comments:[...m.comments]}));
  const intro=clean(g.comments);
  if(moves.length) moves[moves.length-1].comments.push(...intro);
  const p=start.clone();
  for(const n of g.moves.mainline()) {
   const m=parseSan(p,n.san);
   if(!m||!p.isLegal(m)) throw new Error(`Illegal source ${index}: ${n.san}`);
   p.play(m);moves.push({san:n.san,comments:clean([...(n.startingComments||[]),...(n.comments||[])])});
   if(!paths.has(key(p))) paths.set(key(p),moves.map(m=>({...m,comments:[...m.comments]})));
  }
  resolved.set(index,{moves,intro:prefix.length?[]:intro});
 }
}

for(const {g,index} of sources) if(!resolved.has(index)) throw new Error(`Cannot connect source ${index} to initial position`);
const names = {
 1:'Meet the Wizard',2:'The core setup: g4, Qa4, Nxe2',
 3:'Qxa2: Qxa1 and the rook sacrifice',6:'Qxa2: Qxb1 and Rxa7',
 9:'Qxa2: Qxb2 and the a6 checkpoint',12:'Qxd2: Qxb2 and Qxe2',
 13:'Qxd2: Qxb1 and the rook cleanup',15:'Qxd2: Qxc1 and Nxc1',
 17:'Qxd2: Qxe1 and the queen race',20:'Qxd2: immediate Qxe2 checkpoint',
 21:'Qxh1: Nxe7 and the pawn chain',22:'Qxh1: Qxe2 and opening the h-file',
 23:'Qxh1: Qxc1 and the queen escape',25:'Early Qxh1: Bxe2 and keep away',
 27:'Early Qxh1: immediate Qxg1 checkpoint',28:'Early Qxh1: Rxa7 and b4',
 30:'Early Qxa2: capture the queen',33:'Early Qxd2: Kxd2 and Qxf7',
};
const chapters=[],seen=new Set();
for (const {g,index} of sources) {
 const {moves,intro}=resolved.get(index);
 const endpoints=[15,27,39].filter(n=>n<moves.length-4);
 endpoints.push(moves.length);
 for (const end of endpoints) {
  const part=moves.slice(0,end);
  const signature=part.map(m=>m.san.replace(/[+#]/g,'')).join(' ');
  if(seen.has(signature)) continue;
  seen.add(signature);
  const full=end===moves.length;
  const title=names[index]+(endpoints.length>1?(full?' — complete line':` — through move ${Math.ceil(end/2)}`):'');
  const comments=intro.length?intro:['Train as White. Replay this line from the initial position.'];
  chapters.push({title,source:index,moves:part,intro:comments,full});
 }
}
const quote=s=>s.replace(/\\/g,'\\\\').replace(/"/g,'\\"');
const comment=s=>'{ '+s.replace(/[{}]/g,'')+' }';
// Recheck each complete replay from the initial position before emitting files.
for (const chapter of chapters) {
 const p=Antichess.default();
 for (const {san} of chapter.moves) {
  const move=parseSan(p,san);
  if(!move||!p.isLegal(move)) throw new Error(`Illegal replay in ${chapter.title}: ${san}`);
  p.play(move);
 }
}
const pgn=chapters.map(c=>[
 '[Event "Wizard Opening"]','[StudyName "Wizard Opening"]',
 `[ChapterName "${quote(c.title)}"]`,'[Variant "Antichess"]','[Result "*"]',
 '[Annotator "Adapted from Dy1ar’s Lichess study f3NuTHGo"]','',
 c.intro.map(comment).join(' '),
 c.moves.map((m,i)=>`${i%2===0?`${Math.floor(i/2)+1}. `:''}${m.san}${m.comments.length?' '+m.comments.map(comment).join(' '):''}`).join(' ')+' *',
].join('\n')).join('\n\n');
fs.writeFileSync(new URL('../studies/wizard-training.pgn',import.meta.url),pgn+'\n');
fs.writeFileSync(new URL('../src/wizardStudy.ts',import.meta.url),'// Generated by scripts/build-wizard.mjs from the authored study.\nexport const wizardStudy = '+JSON.stringify(pgn)+';\n');
fs.writeFileSync(new URL('../studies/WIZARD_CHAPTERS.md',import.meta.url),
 '# Wizard Opening training module\n\nTrain White. Every chapter replays from the standard initial Antichess position.\n'+
 'Quiz chapters are excluded. Only supplied main lines become drills; side variations remain in wizard-source.pgn.\n'+
 'Early Black deviations described in the source are connected by legally validated opening prefixes.\n'+
 'Long lines grow through checkpoints, then their complete supplied continuation. A checkpoint is not necessarily a win.\n\n'+
 '| Chapter | Lesson | Plies | Source chapter |\n|---|---|---|---|\n'+
 chapters.map((c,i)=>`| ${i+1} | ${c.title} | ${c.moves.length} | ${c.source} |`).join('\n')+'\n');
console.log(`Built ${chapters.length} chapters from ${sources.length} non-quiz source chapters.`);
